import math
# Example Inputs
x = 25.6
y = 3
n = 5
k = 3
p = [1, 2, 3]
q = [4, 5, 6]
# Math Functions
print("Ceiling:", math.ceil(x))
print("Combination:", math.comb(n, k))
print("Sign Copy:", math.copysign(x, -1))
print("Absolute:", math.fabs(x))
print("Factorial:", math.factorial(n))
print("Floor:", math.floor(x))
print("Modulo:", math.fmod(x, y))
print("GCD:", math.gcd(n, k))
print("Square Root:", math.sqrt(x))
print("Logarithm Base 10:", math.log2(x))
print("Distance:", math.dist(p, q))
print("Sine:", math.sin(math.radians(30)))
print("Hyperbolic Cosine:", math.cosh(1))
print("Exponent:", math.exp(2))
print("Gamma:", math.gamma(5))
print("Pi constant:", math.pi)